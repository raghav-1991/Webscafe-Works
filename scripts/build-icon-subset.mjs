/**
 * Generates src/styles/vendor/icons.css — a subset of Phosphor (regular + duotone) and
 * Line Awesome containing only the icon classes referenced in /src.
 * Cuts ~500 KB of CSS from the bundle. Re-run after using new icons:  npm run icons
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/styles/vendor/icons.css');

const walk = (dir) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : /\.(jsx?|tsx?)$/.test(f) ? [p] : [];
  });
const used = new Set();
for (const file of walk(join(root, 'src'))) {
  for (const m of readFileSync(file, 'utf8').matchAll(/\b(ph|la)-[a-z0-9-]+/g)) used.add(m[0]);
}

const sources = [
  { css: 'node_modules/@phosphor-icons/web/src/regular/style.css', iconRe: /^\.ph\.(ph-[\w-]+):(?:before|after)$/ },
  { css: 'node_modules/@phosphor-icons/web/src/duotone/style.css', iconRe: /^\.ph-duotone\.(ph-[\w-]+):(?:before|after)$/ },
  { css: 'node_modules/line-awesome/dist/line-awesome/css/line-awesome.min.css', iconRe: /^\.(la-[\w-]+):(?:before|after)$/ },
];

// e.g. `.la.la-xing{font-family:brands}` or `.ph-duotone.ph-acorn:after`
const ICON_ANY = /^\.(?:ph|ph-duotone|la|lab|lar|las)\.((?:ph|la)-[\w-]+)(?::before|:after)?$/;

let result = '/* AUTO-GENERATED by scripts/build-icon-subset.mjs — do not edit by hand */\n';
for (const { css, iconRe } of sources) {
  const abs = join(root, css);
  const text = readFileSync(abs, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const rel = relative(dirname(out), dirname(abs)).replace(/\\/g, '/');
  for (const [, selector, body] of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const sel = selector.trim();
    if (sel.startsWith('@font-face')) {
      // keep only woff2/woff sources, re-pointed at node_modules
      const urls = [...body.matchAll(/url\(["']?([^"')?#]+)[^)]*\)\s*format\(["']?(woff2|woff)["']?\)/g)];
      const src = urls.map(([, u, f]) => `url("${rel}/${u.replace(/^\.\//, '')}") format("${f}")`).join(',');
      const rest = body.replace(/src\s*:[^;]+;?/g, '').trim();
      result += `@font-face{${rest.endsWith(';') || !rest ? rest : rest + ';'}src:${src};font-display:block}\n`;
      continue;
    }
    if (sel.startsWith('@') || /^(\d|from\b|to\b)/.test(sel)) continue; // keyframes fragments etc.
    const parts = sel.split(',').map((s) => s.trim());
    const names = parts.map((p) => (p.match(iconRe) || p.match(ICON_ANY) || [])[1]);
    if (names.every(Boolean)) {
      // icon-specific rule → keep only if one of its icons is used
      if (names.some((n) => used.has(n))) result += `${sel}{${body.trim()}}\n`;
    } else {
      result += `${sel}{${body.trim()}}\n`; // base / utility rule
    }
  }
}
writeFileSync(out, result);
console.log(`icons.css written — ${used.size} icon classes, ${(result.length / 1024).toFixed(1)} KB`);
